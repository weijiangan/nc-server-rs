//! Preview provider availability — `{nc:}has-preview` (§10.12 / §11.1).
//!
//! Mirrors PHP `PreviewManager::isAvailable()` (`lib/private/PreviewManager.php`),
//! which reports `true` iff **some registered provider** matches the file's
//! mimetype.  A provider is registered only when:
//!
//! 1. its class is in `enabledPreviewProviders` (the system array; when unset
//!    PHP's **default** set applies — `getEnabledDefaultProvider`, `:260-290`), and
//! 2. its per-provider availability holds — a binary on disk (ffmpeg / LibreOffice)
//!    or, for the imagick family, the imagick extension supporting the format.
//!
//! ## Resolved model ([`ProviderRegistry`])
//!
//! | Category | Mimetypes | Gate |
//! |----------|-----------|------|
//! | GD images | `image/png`, `image/jpeg`, `image/gif`, `image/bmp`, `image/x-xbitmap`, `image/webp` | class in enabled list |
//! | Krita | `application/x-krita` | class in enabled list |
//! | Text | `text/plain` (TXT), `text/markdown`+`text/x-markdown` (MarkDown) | class in enabled list |
//! | MP3 | `audio/mpeg` | class in enabled list (NOT in PHP default) |
//! | OpenDocument | `application/vnd.oasis.opendocument.*` | class in enabled list — **no binary** (`OpenDocument extends Bundled`; extracts the ODF-embedded `Thumbnails/thumbnail.png`) |
//! | Video | `video/*` | `Movie` in list **and** ffmpeg binary |
//! | MS Office | `application/msword`, `application/vnd.ms-*`, `application/vnd.openxmlformats-officedocument.*`, `application/vnd.sun.xml.*`, `image/emf` | per-class in list **and** LibreOffice binary |
//! | Imaginary raster set | `image/{bmp,x-bitmap,png,jpeg,gif,heic,heif,svg+xml,tiff,webp}`, `application/illustrator` | Imaginary backend available (URL configured **and** `OC\Preview\Imaginary` in list) |
//! | imagick family | `image/svg+xml`, `image/tiff`, `image/{heic,heif,tga,sgi}`(+`x-`variants), `application/{pdf,illustrator,x-photoshop,postscript,font-sfnt,x-font}` | class in enabled list **and** format supported by PHP's imagick (startup probe); Imaginary additionally covers svg/tiff/heic/heif/illustrator |
//!
//! ## imagick introspection (startup probe)
//!
//! The imagick-backed providers (SVG, TIFF, PDF, Illustrator, Photoshop,
//! Postscript, Font, HEIC, TGA, SGI) are registered in PHP only when the class is
//! enabled **and** the PHP imagick build supports the format
//! (`IMagickSupport::supportsFormat($f) === count(queryFormats($f)) === 1`).  Rust
//! replicates this by probing the PHP build **once at startup** (a single `php -r`
//! call — the same interpreter already used to parse `config.php`) for which of
//! [`IMAGICK_PROBE_FORMATS`] imagick supports, then gating each provider on
//! class-membership **and** that result.  This makes `{nc:}has-preview` faithful on
//! imagick installs — e.g. existing HEIC previews generated by PHP's imagick HEIC
//! delegate are still *requested* by the web gallery even when Imaginary is absent.
//! If `php` is unavailable or the probe fails, imagick is treated as absent (safe
//! under-report).  Note the probe affects the `has-preview` **hint** only: native
//! *generation* (11.4) stays Imaginary-only, so an imagick-only miss still proxies
//! to PHP-FPM (which generates via imagick) — behaviour is never worse than today.
//!
//! ## Deviations from PHP (documented per CLAUDE.md)
//!
//! - **imagick support is snapshotted at startup.** If the PHP imagick build's
//!   format support changes after the server starts (extension install/removal),
//!   the registry is stale until restart. Acceptable: imagick format support is a
//!   deploy-time property, and the failure mode is a stale hint, never wrong content.
//! - **Imaginary availability also requires a valid URL.** PHP registers Imaginary
//!   on list-membership alone and only errors on the URL at generation time; gating
//!   `has-preview` on URL+list upholds the invariant `has-preview ⇒ generatable`
//!   (avoids `has-preview=true` followed by a generation 404 — the failure mode
//!   §11.1 exists to prevent).
//! - **`enabledPreviewProviders` replaces the default set** (not additive) — exactly
//!   PHP's `getSystemValue(key, default)`. Setting it to `[OC\Preview\Movie]`
//!   disables the default image providers. Only listing the abstract `OC\Preview\Image`
//!   re-expands to all GD image providers (PHP's `Image::class` special case).
//! - **Empty binary path = not configured.** PHP's `is_string('')` would register a
//!   provider with a useless empty binary; Rust treats `''` as unset and falls through
//!   to the `$PATH` search (matches intent; the previous Rust behaviour and tests).
//! - **Config class values are trimmed of a leading `\`** before membership checks
//!   (PHP compares untrimmed). A lenient robustness measure that can only enable a
//!   provider the operator clearly intended.
//! - **PATH search only.** Binary resolution uses the config path or a `$PATH` search
//!   (PHP `binaryFinder->findBinaryPath`); PHP's additional hardcoded common-install
//!   directory list is not replicated (under-reports only).
//! - **External-storage `previews` mount option** is not yet wired (no external
//!   storage support); home storage has no mount and PHP defaults the option `true`.

