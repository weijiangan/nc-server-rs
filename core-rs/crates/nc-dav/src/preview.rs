/// Imaginary's exact supported mimetype set (`Imaginary::supportedMimeTypes():44-46`).
///
/// **One source of truth** shared by `{nc:}has-preview` (this module) and native
/// generation (11.4): a mimetype here is Rust-generatable exactly when the Imaginary
/// backend is available.  Note `image/x-bitmap` (Imaginary) is distinct from the GD
/// provider's `image/x-xbitmap` (XBitmap) — different mimetypes, different providers.
pub const IMAGINARY_MIMES: &[&str] = &[
    "image/bmp",
    "image/x-bitmap",
    "image/png",
    "image/jpeg",
    "image/gif",
    "image/heic",
    "image/heif",
    "image/svg+xml",
    "image/tiff",
    "image/webp",
    "application/illustrator",
];

/// Resolved preview-provider gating, built **once** at startup from system config.
///
/// Single source of truth for `{nc:}has-preview` (§11.1) and, later, native
/// generation (11.4) — keeping the property and the generator from ever disagreeing
/// (`rust_generatable(m) ⇒ is_available(m)`).
#[derive(Clone)]
pub struct ProviderRegistry {
    enable_previews: bool,
    /// Enabled provider classes — PHP default applied when the config key is unset,
    /// `Image` base-class expansion applied.  Membership mirrors PHP's
    /// `in_array(trim(class,'\\'), enabled)`.
    enabled: HashSet<String>,
    /// `Movie` provider usable: `preview_ffmpeg_path` set or ffmpeg found on `$PATH`.
    ffmpeg: bool,
    /// MS-Office family usable: `preview_libreoffice_path` set or a LibreOffice /
    /// OpenOffice binary found on `$PATH`.
    libreoffice: bool,
    /// Imaginary backend usable: `preview_imaginary_url` valid **and**
    /// `OC\Preview\Imaginary` in the enabled list.
    imaginary: bool,
    /// Imagick query-formats (uppercase) supported by the PHP imagick build,
    /// detected once at startup by [`detect_imagick_formats`].  Empty when imagick
    /// is absent or the probe failed — which disables the imagick-family providers
    /// (a safe under-report).
    imagick_formats: HashSet<String>,
}

impl ProviderRegistry {
    /// Build from system config, resolving binary availability (config-then-`$PATH`)
    /// and probing the PHP imagick build for supported formats.  Intended to be
    /// called once at startup and shared behind an `Arc`.
    pub fn from_config(cfg: &nc_db::config::NcConfig) -> Self {
        let ffmpeg = resolve_binary(cfg.preview_ffmpeg_path.as_deref(), &["ffmpeg"]);
        let libreoffice = resolve_binary(
            cfg.preview_libreoffice_path.as_deref(),
            &["libreoffice", "soffice", "openoffice"],
        );
        let imagick = detect_imagick_formats(&nc_db::config::resolve_php_binary(
            cfg.php_binary.as_deref(),
        ));
        Self::build(
            cfg.enable_previews,
            cfg.enabled_preview_providers.as_deref(),
            ffmpeg,
            libreoffice,
            imaginary_url_valid(cfg.preview_imaginary_url.as_ref().map(|s| s.expose())),
            &imagick.iter().map(|s| s.as_str()).collect::<Vec<_>>(),
        )
    }

    /// Pure constructor — no `$PATH` search, no `php` probe.  Used by tests and
    /// [`Self::from_config`].  `imagick_formats` are the uppercase query-formats the
    /// PHP imagick build supports (see [`detect_imagick_formats`]).
    pub fn build(
        enable_previews: bool,
        enabled_providers: Option<&[String]>,
        ffmpeg: bool,
        libreoffice: bool,
        imaginary_url_valid: bool,
        imagick_formats: &[&str],
    ) -> Self {
        let enabled = resolve_enabled(enabled_providers);
        let imaginary = imaginary_url_valid && enabled.contains(P_IMAGINARY);
        let imagick_formats = imagick_formats
            .iter()
            .map(|s| s.to_ascii_uppercase())
            .collect();
        Self {
            enable_previews,
            enabled,
            ffmpeg,
            libreoffice,
            imaginary,
            imagick_formats,
        }
    }

    /// Global `enable_previews` system config (default `true`).  When `false`, PHP
    /// throws `NotFoundException('Previews disabled')` → the routes return `404`.
    pub fn enable_previews(&self) -> bool {
        self.enable_previews
    }

    /// Whether the Imaginary backend is usable for native generation (11.4).
    pub fn imaginary_available(&self) -> bool {
        self.imaginary
    }

    /// Can *Rust* generate this mimetype natively?  Strict subset of
    /// [`Self::is_available`]: the Imaginary-supported raster set when the backend
    /// is up.  Drives the 11.4 miss-path decision (else PHP-FPM fallback).
    pub fn rust_generatable(&self, mime: &str) -> bool {
        if !self.enable_previews || !self.imaginary {
            return false;
        }
        let mime = mime.split(';').next().unwrap_or(mime).trim();
        IMAGINARY_MIMES.contains(&mime)
    }

    /// PHP `PreviewManager::isAvailable` — `true` iff some registered provider
    /// matches `mime_type`.  Drives the `{nc:}has-preview` PROPFIND property.
    ///
    /// `is_mounted` carries the external-storage mount state; its `previews`
    /// option is not yet wired (PHP defaults it `true`) — see module docs.
    pub fn is_available(&self, mime_type: &str, _is_mounted: bool) -> bool {
        if !self.enable_previews {
            return false;
        }

        // Strip a charset suffix commonly appended to mimetypes
        // (e.g. "text/plain; charset=utf-8" → "text/plain").
        let mime = mime_type.split(';').next().unwrap_or(mime_type).trim();

        // Imaginary registered ⇒ its whole supported set is available, regardless of
        // the individual GD providers (PHP iterates every matching provider and the
        // first available one wins).
        if self.imaginary && IMAGINARY_MIMES.contains(&mime) {
            return true;
        }

        let e = |p: &str| self.enabled.contains(p);
        // imagick format supported by the PHP build (startup probe).
        let im = |fmt: &str| self.imagick_formats.contains(fmt);

        match mime {
            // GD image providers — class membership only.
            "image/png" => e(P_PNG),
            "image/jpeg" => e(P_JPEG),
            "image/gif" => e(P_GIF),
            "image/bmp" => e(P_BMP),
            "image/x-xbitmap" => e(P_XBITMAP),
            "image/webp" => e(P_WEBP),
            "application/x-krita" => e(P_KRITA),

            // Text providers.
            "text/plain" => e(P_TXT),
            "text/markdown" | "text/x-markdown" => e(P_MARKDOWN),

            // MP3 (not in PHP's default provider set).
            "audio/mpeg" | "audio/mp3" => e(P_MP3),

            // OpenDocument extends Bundled — extracts the ODF-embedded thumbnail,
            // needs NO office binary (unlike the MSOffice family below).
            _ if mime.starts_with("application/vnd.oasis.opendocument.") => e(P_OPENDOCUMENT),

            // HEIC/HEIF via the imagick HEIC delegate (PHP regex `/image\/(x-)?hei(f|c)/`).
            // Imaginary, when available, also covers these via the early return above.
            "image/heic" | "image/heif" | "image/x-heic" | "image/x-heif"
            | "image/heic-sequence" | "image/heif-sequence" => e(P_HEIC) && im("HEIC"),

            // Video: Movie provider, gated on the list and the ffmpeg binary.
            _ if mime.starts_with("video/") => e(P_MOVIE) && self.ffmpeg,

            // MS-Office family (extends Office): per-class list gate + LibreOffice.
            "application/msword" => e(P_MSOFFICEDOC) && self.libreoffice,
            "image/emf" => e(P_EMF) && self.libreoffice,
            _ if mime.starts_with("application/vnd.ms-") => e(P_MSOFFICE2003) && self.libreoffice,
            _ if mime.starts_with("application/vnd.openxmlformats-officedocument.") => {
                e(P_MSOFFICE2007) && self.libreoffice
            }
            _ if mime.starts_with("application/vnd.sun.xml.") => {
                e(P_STAROFFICE) && self.libreoffice
            }

            // ── imagick-backed providers ─────────────────────────────────────
            // Registered in PHP only when the class is enabled AND the PHP imagick
            // build supports the format (`supportsFormat` ≡ `queryFormats(f)==1`),
            // detected here via the startup probe.  Imaginary additionally covers
            // svg/tiff/heic/heif/illustrator through the early return above; these
            // arms supply the imagick path (and the formats Imaginary never covers:
            // pdf, photoshop, postscript, font, tga, sgi).
            "image/svg+xml" => e(P_SVG) && im("SVG"),
            "image/tiff" => e(P_TIFF) && im("TIFF"),
            "application/illustrator" => e(P_ILLUSTRATOR) && im("AI"),
            "application/x-photoshop" => e(P_PHOTOSHOP) && im("PSD"),
            "application/postscript" => e(P_POSTSCRIPT) && im("EPS"),
            "application/pdf" => e(P_PDF) && im("PDF"),
            // Font provider regex: `/application\/(?:font-sfnt|x-font$)/` — note this
            // is NOT `font/*` (e.g. `font/ttf` has no PHP provider → false).
            "application/font-sfnt" | "application/x-font" => e(P_FONT) && im("TTF"),
            // TGA: `/image\/(x-)?t(ar)?ga/`
            "image/tga" | "image/x-tga" | "image/targa" | "image/x-targa" => {
                e(P_TGA) && im("TGA")
            }
            // SGI: `/image\/(x-)?sgi/`
            "image/sgi" | "image/x-sgi" => e(P_SGI) && im("SGI"),

            // Everything else has no provider.
            _ => false,
        }
    }
}

/// Resolve the enabled provider set from config, applying PHP's default when unset
/// and the `Image` base-class expansion (`PreviewManager::getEnabledDefaultProvider`).
fn resolve_enabled(configured: Option<&[String]>) -> HashSet<String> {
    let mut set: HashSet<String> = match configured {
        // Config key set → replaces the default set entirely (PHP `getSystemValue`).
        Some(list) => list
            .iter()
            .map(|c| c.trim_start_matches('\\').to_string())
            .collect(),
        // Unset → PHP default: MarkDown, TXT, OpenDocument + the GD image providers.
        None => [
            P_MARKDOWN,
            P_TXT,
            P_OPENDOCUMENT,
            P_PNG,
            P_JPEG,
            P_GIF,
            P_BMP,
            P_XBITMAP,
            P_KRITA,
            P_WEBP,
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
    };

    // PHP: listing the abstract `Image` base class expands to all GD image providers.
    if set.contains(P_IMAGE) {
        for p in [P_PNG, P_JPEG, P_GIF, P_BMP, P_XBITMAP, P_KRITA, P_WEBP] {
            set.insert(p.to_string());
        }
    }
    set
}

/// PHP treats the default `'invalid'` and the empty string as "not configured"
/// (`Imaginary::getCroppedThumbnail` logs an error and returns null on `'invalid'`).
fn imaginary_url_valid(url: Option<&str>) -> bool {
    matches!(url, Some(u) if !u.is_empty() && u != "invalid")
}

/// Probe the **PHP** imagick build once for the query-formats it supports,
/// replicating `IMagickSupport::supportsFormat` (`count(queryFormats($f)) === 1`)
/// for each format in [`IMAGICK_PROBE_FORMATS`].  Returns uppercase format names.
///
/// Any failure (interpreter missing, non-zero exit, imagick absent) yields an
/// empty set, which disables the imagick-family providers — a safe under-report
/// (a stale or missing hint degrades to a generic icon, never wrong content;
/// generation of imagick-only types still proxies to PHP-FPM).
fn detect_imagick_formats(php: &str) -> Vec<String> {
    // Build the format list literal for the PHP snippet from the shared constant so
    // the probe and the Rust model can never drift apart.
    let list = IMAGICK_PROBE_FORMATS
        .iter()
        .map(|f| format!("'{f}'"))
        .collect::<Vec<_>>()
        .join(",");
    let script = format!(
        "if (!extension_loaded('imagick')) {{ exit(0); }} \
         try {{ $i = new Imagick(); }} catch (Throwable $e) {{ exit(0); }} \
         foreach ([{list}] as $f) {{ \
             if (count($i->queryFormats($f)) === 1) {{ echo $f, ','; }} \
         }}"
    );
    match std::process::Command::new(php).arg("-r").arg(&script).output() {
        Ok(out) if out.status.success() => {
            parse_imagick_probe(&String::from_utf8_lossy(&out.stdout))
        }
        Ok(out) => {
            tracing::debug!(
                "imagick probe ({php}) exited non-zero; imagick treated as unavailable: {}",
                String::from_utf8_lossy(&out.stderr).trim()
            );
            Vec::new()
        }
        Err(e) => {
            tracing::debug!("imagick probe could not run {php} ({e}); imagick treated as unavailable");
            Vec::new()
        }
    }
}

/// Parse the probe's comma-separated stdout (e.g. `"SVG,TIFF,HEIC,"`) into
/// uppercase format names.  Pure — unit-tested independently of the `php` call.
fn parse_imagick_probe(stdout: &str) -> Vec<String> {
    stdout
        .split(',')
        .map(|s| s.trim().to_ascii_uppercase())
        .filter(|s| !s.is_empty())
        .collect()
}

/// Resolve a preview binary: an explicit (non-empty) config path wins; otherwise
/// search `$PATH`.  Mirrors PHP `binaryFinder->findBinaryPath`.
fn resolve_binary(config_path: Option<&str>, names: &[&str]) -> bool {
    if let Some(p) = config_path {
        if !p.is_empty() {
            return true;
        }
    }
    names.iter().any(|n| on_path(n))
}

fn on_path(name: &str) -> bool {
    let Some(path) = std::env::var_os("PATH") else {
        return false;
    };
    std::env::split_paths(&path).any(|dir| is_executable(&dir.join(name)))
}

#[cfg(unix)]
fn is_executable(p: &std::path::Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    match std::fs::metadata(p) {
        Ok(m) => m.is_file() && m.permissions().mode() & 0o111 != 0,
        Err(_) => false,
    }
}

#[cfg(not(unix))]
fn is_executable(p: &std::path::Path) -> bool {
    p.is_file()
}

